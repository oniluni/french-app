// Hand-written part of the «Справочник» tab: what Lexique and WikDict do not give, or give wrong.
//
// - OWN_WORDS: the function words Lexique lists, with their translation as the kind they are
//   listed under and what they are for. WikDict has no such thing: "car" is «автобус» there, and
//   "au" is only «слитная форма» in the lessons.
// - EXTRA_WORDS: function words Lexique does not list under the kind: compound prepositions and
//   conjunctions, and "que", which Lexique knows only as a pronoun.
// - PHRASES: kinds of expression. French has no phrasal verbs; the nearest things are a verb with
//   its preposition and a verb with en or y.
//
// One entry per line: `French = Russian`, or `French = Russian | what the word is for`.
// The most common first: that is the order of the hand-written lists.
// An expression has no punctuation at its end and no "qqn"/"qqch": the reader reads it and the
// phone says it aloud.

/** "fr = ru | use" lines → [{ fr, ru, use? }]. */
export function pairs(text) {
  return text.trim().split('\n').map((line) => {
    const at = line.indexOf(' = ');
    if (at < 0) throw new Error(`reference-own.mjs: no " = " in the line "${line}"`);
    const [ru, use, ...more] = line.slice(at + 3).split('|').map((part) => part.trim());
    const fr = line.slice(0, at).trim();
    if (!fr || !ru || use === '' || more.length) throw new Error(`reference-own.mjs: the line "${line}" lacks a side or has two "|"`);
    return { fr, ru, ...(use ? { use } : {}) };
  });
}

