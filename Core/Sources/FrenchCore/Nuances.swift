import Foundation

/// A short note on a word that has several close Russian equivalents: when to choose which.
public struct Nuance: Decodable, Hashable, Sendable {
    /// The French lemma the note belongs to.
    public let fr: String
    /// A compact gloss, such as «идти, ехать».
    public let title: String
    /// The distinction in plain Russian.
    public let text: String
    /// French examples with their translations, one per line.
    public let examples: [String]

    public init(fr: String, title: String, text: String, examples: [String] = []) {
        self.fr = fr
        self.title = title
        self.text = text
        self.examples = examples
    }

    private enum CodingKeys: String, CodingKey {
        case fr, title, text, examples
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        fr = try container.decode(String.self, forKey: .fr)
        title = try container.decode(String.self, forKey: .title)
        text = try container.decode(String.self, forKey: .text)
        examples = try container.decodeIfPresent([String].self, forKey: .examples) ?? []
    }
}

/// The hand-written usage notes, bundled as `nuances.json` and generated by
/// `tools/build-nuances.mjs`.
public struct Nuances: Sendable {
    private let byKey: [String: [Nuance]]

    public init(notes: [Nuance] = []) {
        byKey = Dictionary(grouping: notes) { Lexicon.key(Content.bare($0.fr)) }
    }

    public init(data: Data) throws {
        struct File: Decodable { let notes: [Nuance] }
        self.init(notes: try JSONDecoder().decode(File.self, from: data).notes)
    }

    /// Notes for a word or any of its forms; an article and punctuation do not matter.
    public func notes(for word: String) -> [Nuance] {
        let key = Lexicon.key(Content.bare(word))
        return byKey[key] ?? byKey[Lexicon.key(word)] ?? []
    }
}
